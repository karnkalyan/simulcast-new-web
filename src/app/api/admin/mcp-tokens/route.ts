import { NextResponse } from "next/server";
import { getSession } from "@/lib/auth";
import { prisma } from "@/lib/db";
import { createMcpToken } from "@/lib/mcp-auth";

export const dynamic = "force-dynamic";

export async function GET() {
  const admin = await getSession();
  if (!admin || admin.role !== "ADMIN") {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  try {
    const tokens = await prisma.apiToken.findMany({
      orderBy: { createdAt: "desc" },
    });
    return NextResponse.json({ tokens });
  } catch (err) {
    console.error(err);
    return NextResponse.json({ error: "Failed to fetch tokens" }, { status: 500 });
  }
}

export async function POST(request: Request) {
  const admin = await getSession();
  if (!admin || admin.role !== "ADMIN") {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  try {
    const { name, expiresIn = "30d" } = await request.json();
    if (!name) {
      return NextResponse.json({ error: "Token name required" }, { status: 400 });
    }

    const jwtToken = await createMcpToken({ name, expiresIn });

    const record = await prisma.apiToken.create({
      data: {
        name,
        token: jwtToken.slice(0, 180), // Store safe prefix/hash
        role: "MCP_CLIENT",
        description: `Generated by ${admin.email} on ${new Date().toLocaleDateString()}`,
      },
    });

    return NextResponse.json({ ok: true, token: jwtToken, record });
  } catch (err) {
    console.error(err);
    return NextResponse.json({ error: "Failed to create token" }, { status: 500 });
  }
}

export async function DELETE(request: Request) {
  const admin = await getSession();
  if (!admin || admin.role !== "ADMIN") {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  try {
    const { id } = await request.json();
    if (!id) return NextResponse.json({ error: "ID required" }, { status: 400 });

    await prisma.apiToken.update({
      where: { id },
      data: { revoked: true },
    });

    return NextResponse.json({ ok: true });
  } catch (err) {
    console.error(err);
    return NextResponse.json({ error: "Failed to revoke token" }, { status: 500 });
  }
}
